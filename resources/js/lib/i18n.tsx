const dictionaries: Record<Locale, Record<string, string>> = { en, am };

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
    let text = dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key;
    if (vars) {
        Object.entries(vars).forEach(([k, v]) => {
            text = text.replace(`:${k}`, String(v));
        });
    }
    return text;
}

type I18nContextValue = {
    locale: Locale;
    t: (key: string, vars?: Record<string, string | number>) => string;
    setLocale: (locale: Locale) => void;
};

const I18nContext = createContext<I18nContextValue>({
    locale: 'en',
    t: (key) => translate('en', key),
    setLocale: () => undefined,
});

export function I18nProvider({ locale, children }: { locale: string; children: React.ReactNode }) {
    const current: Locale = locale === 'am' ? 'am' : 'en';

    const setLocale = useCallback((next: Locale) => {
        router.post(
            '/settings/language',
            { language: next },
            { preserveState: true, preserveScroll: true, only: [], headers: { 'X-Inertia': 'true' } },
        );
    }, []);

    const value = useMemo<I18nContextValue>(
        () => ({
            locale: current,
            t: (key, vars) => translate(current, key, vars),
            setLocale,
        }),
        [current, setLocale],
    );

    return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useTranslation() {
    return useContext(I18nContext);
}
